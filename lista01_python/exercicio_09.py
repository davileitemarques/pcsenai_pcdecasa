#Atribuindo um valor base as variaveis
copo1 = "laranja"
copo2 = "acerola"
#Imprime o valor atual das variaveis
print(f"O copo um tem suco de {copo1} e o dois tem suco de {copo2}")
#Fazendo a troca de valores com o auxilio de uma variavel "auxiliar"
auxiliar = copo1
copo1 = copo2
copo2 = auxiliar
#Imprime os novos valores atibuidos as variaveis
print(f"Agora o copo um tem suco de {copo1} e o dois tem suco de {copo2}")